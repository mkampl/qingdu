"""
UserWord snapshot backfill — re-runs `lookup_pinyin_meaning` against
the current dictionaries and rewrites stale row snapshots in place.
"""

import pytest

from app.database import User, UserWord
from app.services import snapshot_backfill


@pytest.fixture
def db_session(memory_db):
    s = memory_db()
    s.add(User(id=1, username="alice", password_hash="x", invite_quota=0))
    s.commit()
    yield s
    s.close()


@pytest.fixture
def fake_dictionaries(swap_dictionaries):
    """Stub hsk_vocab + cedict_vocab so the backfill has a known target
    to rewrite to."""
    swap_dictionaries(
        hsk={
            "地": {
                "pinyin": "dì",
                "meaning": "earth",
                "meanings": ["earth", "ground"],
                "level_new": "new-1",
            },
        },
        cedict={},
    )


def test_backfill_overwrites_stale_meaning(db_session, fake_dictionaries):
    db_session.add(
        UserWord(
            user_id=1,
            word="地",
            state="learning",
            pinyin="de",
            meaning="-ly",  # stale snapshot from an older dictionary parse
        )
    )
    db_session.commit()

    n = snapshot_backfill.refresh_all_user_words(db_session)
    assert n == 1

    row = db_session.query(UserWord).filter(UserWord.word == "地").one()
    assert row.meaning == "earth"
    assert row.pinyin == "dì"


def test_backfill_is_idempotent(db_session, fake_dictionaries):
    from app.database import UserWordGloss

    row = UserWord(user_id=1, word="地", state="learning", pinyin="dì", meaning="earth")
    db_session.add(row)
    db_session.commit()
    # Seed the dictionary gloss too: backfill compares against that row
    # as well as the snapshot columns.
    db_session.add(
        UserWordGloss(
            user_word_id=row.id,
            pinyin="dì",
            meaning="earth",
            source="dictionary",
        )
    )
    db_session.commit()

    # Snapshot already matches the dictionary — no writes expected.
    assert snapshot_backfill.refresh_all_user_words(db_session) == 0


def test_backfill_preserves_meaning_when_dictionary_has_nothing(db_session, fake_dictionaries):
    """A word not in any dictionary today should keep its existing meaning
    — pypinyin would produce a (pinyin-only, empty-meaning) fallback that
    would otherwise wipe a cached translation from an earlier session."""
    db_session.add(
        UserWord(
            user_id=1,
            word="奇怪",
            state="learning",
            pinyin="qí guài",
            meaning="strange (cached translation)",
        )
    )
    db_session.commit()

    snapshot_backfill.refresh_all_user_words(db_session)
    row = db_session.query(UserWord).filter(UserWord.word == "奇怪").one()
    # Pinyin can be regenerated by pypinyin without loss of info, but the
    # meaning should be preserved since the dictionary has nothing better.
    assert row.meaning == "strange (cached translation)"


def test_backfill_leaves_package_sourced_snapshot_alone(db_session, fake_dictionaries):
    """A row whose headline meaning came from a curated package keeps it;
    only the dictionary gloss row is refreshed underneath."""
    from app.database import UserWordGloss

    row = UserWord(
        user_id=1,
        word="地",
        state="learning",
        pinyin="de",
        meaning="particle: -ly (package)",
        meaning_source="package",
    )
    db_session.add(row)
    db_session.commit()
    db_session.add(
        UserWordGloss(
            user_word_id=row.id,
            pinyin="de",
            meaning="particle: -ly (package)",
            source="package",
            source_tag="some_package",
        )
    )
    db_session.commit()

    snapshot_backfill.refresh_all_user_words(db_session)
    snapshot_backfill.refresh_all_user_words(db_session)

    row = db_session.query(UserWord).filter(UserWord.word == "地").one()
    assert row.meaning == "particle: -ly (package)"
    assert row.pinyin == "de"
    by_source = {g.source: g for g in row.glosses}
    assert by_source["package"].meaning == "particle: -ly (package)"
    assert by_source["dictionary"].meaning == "earth"
    # Idempotent: a third pass has nothing to write.
    assert snapshot_backfill.refresh_all_user_words(db_session) == 0
